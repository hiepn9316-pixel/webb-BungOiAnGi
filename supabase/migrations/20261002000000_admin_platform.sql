drop policy if exists "Users can read own profile and admins can read all" on public.profiles;
create policy "Users can read own profile and admins can read all"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists "Users can update own profile name" on public.profiles;
create policy "Users can update own profile name"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

drop policy if exists "Anyone can read dishes" on public.dishes;
create policy "Anyone can read dishes"
  on public.dishes for select to anon, authenticated
  using (true);

drop policy if exists "Admins can manage dishes" on public.dishes;
create policy "Admins can manage dishes"
  on public.dishes for all to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "Users can manage own favorites" on public.favorites;
create policy "Users can manage own favorites"
  on public.favorites for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "Users can manage own history" on public.history;
create policy "Users can manage own history"
  on public.history for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

